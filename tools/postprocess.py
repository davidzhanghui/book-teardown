def head_anchor(h):
    """找 </head> 前最后一个 </style>，返回从该行首到 </head> 的整段。

    favicon 插入的是 <link> 行、back-home(文章页)插入的是 NAV <style> 块，
    都会落在主 </style> 之后。所以锚点必须动态定位最后一个 </style>，
    不能写死 "  </style>\\n</head>" 这类常量（目录页缩进还不一样）。
    """
    i = h.rfind("</style>")
    assert i != -1
    ls = h.rfind("\n", 0, i) + 1
    style_indent = h[ls:i]
    assert style_indent.strip() == "", repr(style_indent)
    j = h.index("</head>", i)
    anchor = h[ls:j + len("</head>")]
    assert h.count(anchor) == 1, repr(anchor[-80:])
    return anchor


def split_head(h, anchor):
    style_indent = anchor.split("</style>")[0]
    head_indent = anchor.split("\n")[-1].split("</head>")[0]
    return style_indent, head_indent
