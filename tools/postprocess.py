def doc_date(html):
    m = re.search(r"更新于 (\d{4}-\d{2}-\d{2})", html)
    return m.group(1) if m else "2026-09-20"


def need(h, item, is_index):
    """该文件是否还缺这一项。"""
    if item == "brand":
        return BRAND_OLD in h
    if item == "github-btn":
        return "github.com/davidzhanghui" not in h
    if item == "favicon":
        return "assets/icon.svg" not in h
    if item == "back-home":
        return "back-home" not in h
    if item == "footer":
        return FOOTER_OLD in h
    if item == "seo":
        return S.MARK_S not in h
    raise ValueError(item)


def apply(h, item, book, is_index):
    if item == "brand":
        assert h.count(BRAND_OLD) == 1
        return h.replace(BRAND_OLD, BRAND_NEW)
    if item == "github-btn":
        assert h.count(LINK_LINE) == 1
        h = h.replace(LINK_LINE, LINK_LINE + SYMS)
        assert h.count(PRINT_BTN) == 1
        return h.replace(PRINT_BTN, GITHUB_BTN + PRINT_BTN)
    if item == "favicon":
        anchor = head_anchor(h)
        style_indent, head_indent = split_head(h, anchor)
        tails = [ln for ln in FAVICON.rstrip("\n").split("\n")]
        block = "\n".join(style_indent + ln if ln.strip() else ln for ln in tails) + "\n"
        new_tail = style_indent + "</style>\n" + block + head_indent + "</head>"
        assert anchor.endswith("</head>")
        return h.replace(anchor, new_tail)
    if item == "back-home":
        if is_index:
            assert IDX_ANCHOR in h
            h = h.replace(IDX_ANCHOR, IDX_ANCHOR + IDX_EXTRA)
            link = ('      <a class="back-home" href="../index.html">← 返回书籍总目录</a>\n\n')
            assert h.count(DOC_HEADER) == 1
            return h.replace(DOC_HEADER, DOC_HEADER + link)
        link = (f'      <a class="back-home" href="index.html">← 返回《{book}》系列目录</a>\n\n')
        assert h.count(DOC_HEADER) == 1
        h = h.replace(DOC_HEADER, DOC_HEADER + link)
        anchor = head_anchor(h)
        style_indent, _ = split_head(h, anchor)
        nav = "\n".join((style_indent + ln if ln.strip() else ln)
                        for ln in NAV.rstrip("\n").split("\n")) + "\n"
        inner = anchor[:anchor.index("</head>")]
        return h.replace(anchor, inner + nav + anchor[len(inner):])
    if item == "footer":
        assert FOOTER_OLD in h
        return h.replace(FOOTER_OLD, FOOTER_NEW)
    raise ValueError(item)


def apply_seo(h, rel, kind, book, bdesc, date, ld):
    """SEO 块插到 </head> 前。文章页顺序固定：NAV 样式 -> SEO 块 -> favicon。

    注意：need() 用 "back-home" 字符串判断 NAV 样式是否缺失，
    所以 back-home 链接插入时必须连 NAV 样式一起落盘。
    """
    block = S.build_block(rel, kind, S.page_title(h) or book, bdesc or "", date, ld) + "\n"
    anchor = head_anchor(h)
    style_indent, head_indent = split_head(h, anchor)
    block = "\n".join((style_indent + ln if ln.strip() else ln)
                       for ln in block.rstrip("\n").split("\n")) + "\n"
    if kind == "collection" and rel.name == "index.html":
        # 目录页顺序（与旧书一致）：SEO 块 -> favicon。
        # favicon 步骤先插了 favicon，这里把 SEO 块插到 favicon 之前。
        fav_lines = [ln for ln in FAVICON.rstrip("\n").split("\n")]
        first_fav = style_indent + fav_lines[0]
        if first_fav in h:
            for ln in fav_lines:
                h = h.replace(style_indent + ln + "\n", "", 1)
            anchor = head_anchor(h)
            style_indent, head_indent = split_head(h, anchor)
            block = "\n".join((style_indent + ln if ln.strip() else ln)
                               for ln in block.rstrip("\n").split("\n")) + "\n"
            fav_block = "\n".join(style_indent + ln for ln in fav_lines)
            new_tail = (style_indent + "</style>\n" + block.rstrip("\n")
                        + "\n" + fav_block + "\n" + head_indent + "</head>")
            return h.replace(anchor, new_tail)
        new_tail = style_indent + "</style>\n" + block + head_indent + "</head>"
        return h.replace(anchor, new_tail)
    assert "<!-- NAV-INJECT:START -->" in h, "文章页先做 back-home 再做 seo"
    assert "assets/icon.svg" in h, "文章页先做 favicon 再做 seo"
    nav_end = style_indent + "<!-- NAV-INJECT:END -->"
    assert nav_end in h
    # 标准顺序（与旧书一致）：NAV 样式 -> SEO 块 -> favicon。
    # back-home 步骤把 NAV 插在 head 尾（favicon 之后），SEO 块先跟在
    # NAV 后面，最后把 favicon 三行搬到 SEO 块之后，还原旧书顺序。
    fav_lines = [ln for ln in FAVICON.rstrip("\n").split("\n")]
    first_fav = style_indent + fav_lines[0]
    assert first_fav in h, "favicon 应已由 favicon 步骤插入"
    block = "\n".join((style_indent + ln if ln.strip() else ln)
                       for ln in block.rstrip("\n").split("\n")) + "\n"
    h = h.replace(nav_end, nav_end + "\n" + block.rstrip("\n"), 1)
    for ln in fav_lines:
        h = h.replace(style_indent + ln + "\n", "", 1)
    fav_block = "\n".join(style_indent + ln for ln in fav_lines)
    anchor2 = head_anchor(h)
    inner2 = anchor2[:anchor2.index("</head>")]
    inner3 = inner2.rstrip("\n") + "\n" + fav_block + "\n"
    tail = anchor2[len(inner2):]
    return h.replace(anchor2, inner3 + tail)


