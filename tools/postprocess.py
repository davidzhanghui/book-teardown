# <div class="part-head"><span class="part-no">第N部分</span><h2 id="gN">名称</h2></div>
# <div class="card-grid"> ...cards... </div>   （卡片内无 div，可直接非贪婪匹配）
PART_RE = re.compile(
    r'<div class="part-head"><span class="part-no">([^<]*)</span>'
    r'<h2 id="g\d+">([^<]*)</h2></div>\s*<div class="card-grid">(.*?)</div>',
    re.S)


def article_count(d):
    """卡片上的「N 篇」= md 数去掉 00 导读和 _/. 开头的内部稿。"""
    return len([p for p in d.glob("*.md")
                if not p.name.startswith(("00", "_", "."))])


def card_book_title(book):
    """书名里已含《》时内层换成〈〉，避免《马克思与《资本论》》。"""
    return book.replace("《", "〈").replace("》", "〉")


def load_cat_conf():
    """tools/books.json：{"<书目录名>": {"cat": "<部分名>", "desc": "<可选文案>"}}"""
    if CATS_CONF.exists():
        return json.loads(CATS_CONF.read_text(encoding="utf-8"))
    return {}


def sync_catalog(root):
    """根 index.html：给缺卡片的书补卡、重排卡号、刷新统计。返回新增书目。"""
    master = root / "index.html"
    s = master.read_text(encoding="utf-8")
    parts = list(PART_RE.finditer(s))
    if not parts:
        print("catalog: 未找到 part-head/card-grid 结构，跳过")
        return []
    have = set(re.findall(r'href="([^"]+)/index\.html"', s))
    book_dirs = [d for d in sorted(root.iterdir())
                 if d.is_dir() and (d / "index.html").exists()
                 and not d.name.startswith(("_", "."))
                 and article_count(d) > 0]
    missing = [d.name for d in book_dirs if d.name not in have]
    if not missing:
        print("catalog: 卡片齐全")
    conf = load_cat_conf()
    inserts = []          # (pos, text) 统一按位置降序应用
    for name in missing:
        info = conf.get(name, {})
        cat = info.get("cat")
        target = next((p for p in parts if p.group(2) == cat), None)
        if target is None:
            target = parts[-1]
            print(f"catalog: {name} 未在 books.json 配分类，"
                  f"暂放入「{target.group(2)}」，请修正后重跑或手工移动")
        desc = info.get("desc") or S.truncate(S.book_desc(root / name), 130)
        card = CARD_T.format(dir=name, num=0, n=article_count(root / name),
                             title=card_book_title(name), desc=desc)
        inserts.append((target.end(3), card))
        print(f"catalog: +卡片《{name}》 → {target.group(2)}")
    for pos, text in sorted(inserts, reverse=True):
        s = s[:pos] + text + s[pos:]
    # 卡号按文档顺序重排
    total = len(re.findall(r'class="book-card"', s))
    it = iter(range(1, total + 1))
    s = re.sub(r'<span class="card-num">\d+</span>',
               lambda m: f'<span class="card-num">{next(it)}</span>', s)
    # 统计文案
    nb = total
    arts = sum(article_count(root / d.name) for d in book_dirs)
    s = re.sub(r'\d+ 本书', f'{nb} 本书', s, count=1)
    s = re.sub(r'共 \d+ 篇解读', f'共 {arts} 篇解读', s)
    s = re.sub(r'共 \d+ 个系列 · \d+ 篇解读',
               f'共 {nb} 个系列 · {arts} 篇解读', s)
    # 侧栏分类链接附书目数（幂等：先剥掉旧计数再重写）
    cnt = {m.group(2): len(re.findall(r'class="book-card"', m.group(3)))
           for m in PART_RE.finditer(s)}
    id2name = dict(re.findall(r'<h2 id="(g\d+)">([^<]*)</h2>', s))

    def _toc(m):
        name = id2name.get(m.group(1))
        if name is None:
            return m.group(0)
        base = re.sub(r'（\d+）$', '', m.group(2))
        return (f'<a href="#{m.group(1)}" class="lvl-2">'
                f'{base}（{cnt.get(name, 0)}）</a>')

    s = re.sub(r'<a href="#(g\d+)" class="lvl-2">([^<]+)</a>', _toc, s)
    master.write_text(s, encoding="utf-8")
    print(f"catalog: {nb} 本书 · {arts} 篇")
    return missing


def sync_readme(root):
    """README：重建「收录书籍」分类表并同步计数（书目顺序取自 index.html）。"""
    rm = root / "README.md"
    if not rm.exists():
        return
    s = rm.read_text(encoding="utf-8")
    ms = (root / "index.html").read_text(encoding="utf-8")
    rows = []
    nb, arts = 0, 0
    for m in PART_RE.finditer(ms):
        dirs = re.findall(r'href="([^"]+)/index\.html"', m.group(3))
        dirs = [d for d in dirs if (root / d).is_dir()]
        if not dirs:
            continue
        nb += len(dirs)
        arts += sum(article_count(root / d) for d in dirs)
        rows.append(f"| {m.group(2)} | {' · '.join(dirs)} |")
    if not rows:
        return
    table = "| 分类 | 书目 |\n|---|---|\n" + "\n".join(rows)
    s = re.sub(r'\| 分类 \| 书目 \|.*?(?=\n## |\Z)', table + "\n", s, flags=re.S)
    s = re.sub(r'（\d+ 个系列 · \d+ 篇解读）', f'（{nb} 个系列 · {arts} 篇解读）', s)
    s = re.sub(r'共 \d+ 个书籍目录', f'共 {nb} 个书籍目录', s)
    s = re.sub(r'收录书籍（\d+ 本）', f'收录书籍（{nb} 本）', s)
    rm.write_text(s, encoding="utf-8")
    print(f"readme: 收录书籍表 {nb} 本已同步")


def process_book(book, check_only, stats, root=None):
    root = root or ROOT
    prev_seo_root = S.ROOT
    S.ROOT = root
    try:
        return _process_book(book, check_only, stats, root)
    finally:
        S.ROOT = prev_seo_root


def _process_book(book, check_only, stats, root):
    d = root / book
    if not d.is_dir():
        print(f"skip (not a dir): {book}")
        return None
    arts = S.article_files(d)
    idx = d / "index.html"
    if not arts or not idx.exists():
        print(f"skip (no html in): {book}")
        return None
    bdesc = S.truncate(S.book_desc(d))
    sib_rels = [a.relative_to(root) for a in arts]

    targets = [(a, False) for a in arts] + [(idx, True)]
    for path, is_index in targets:
        h = path.read_text(encoding="utf-8")
        missing = [it for it in ITEMS if need(h, it, is_index)]
        if is_index and "NAV-INJECT" in h:
            pass
        for it in missing:
            stats["missing"][it] += 1
        if check_only or not missing:
            for it in (missing if check_only else []):
                stats["files"][str(path.relative_to(root))] = missing
            if not missing:
                stats["ok"] += 1
            continue
        for it in missing:
            if it == "seo":
                continue
            h = apply(h, it, book, is_index)
        if "seo" in missing:
            rel = path.relative_to(root)
            date = doc_date(h)
            if is_index:
                ld = S.ld_book_index(rel, book, bdesc, date, arts)
                h = apply_seo(h, rel, "collection", book, bdesc, date, ld)
            else:
                desc = seo_desc(h, bdesc)
                ld = S.ld_article(rel, S.page_title(h) or path.stem, desc, book, date, sib_rels)
                h = apply_seo(h, rel, "article", book, desc, date, ld)
        path.write_text(h, encoding="utf-8")
        stats["changed"] += 1
        stats["files"][str(path.relative_to(root))] = missing
    return (bdesc, arts)


def all_book_dirs(root):
    return [d.name for d in sorted(root.iterdir())
            if d.is_dir() and (d / "index.html").exists()
            and not d.name.startswith(("_", "."))]


def main():
    ap = argparse.ArgumentParser(description="skill 模板 HTML -> 站点标准形态后处理")
    ap.add_argument("books", nargs="*",
                    help="书目录名，可多个；不指定则处理全部书目录")
    ap.add_argument("--check", action="store_true", help="只检查缺项，不写盘")
    args = ap.parse_args()
    books = args.books or all_book_dirs(ROOT)
    if not books:
        ap.error("没有找到任何含 index.html 的书目录")

    stats = {"changed": 0, "ok": 0, "missing": {it: 0 for it in ITEMS}, "files": {}}
    done = []
    for book in books:
        r = process_book(book, args.check, stats)
        if r:
            done.append((book, r[0], r[1]))
    if args.check:
        print(f"checked books={len(done)} ok={stats['ok']}")
        for it in ITEMS:
            print(f"  missing {it}: {stats['missing'][it]}")
        have = set(re.findall(r'href="([^"]+)/index\.html"',
                              (ROOT / "index.html").read_text(encoding="utf-8")))
        for b in all_book_dirs(ROOT):
            if b not in have and article_count(ROOT / b) > 0:
                print(f"  缺总目录卡片: {b}")
        return

    if done:
        sm = ROOT / "sitemap.xml"
        s = sm.read_text(encoding="utf-8")
        added = 0
        for book, bdesc, arts in done:
            d = ROOT / book
            entries = [(d / "index.html", "0.8")] + [(a, "0.6") for a in arts]
            for p, pr in entries:
                rel = p.relative_to(ROOT)
                loc = S.url_for(rel)
                if loc in s:
                    continue
                h = p.read_text(encoding="utf-8")
                line = (f"  <url><loc>{loc}</loc><lastmod>{doc_date(h)}</lastmod>"
                        f"<priority>{pr}</priority></url>")
                s = s.replace("</urlset>", line + "\n</urlset>")
                added += 1
        if added:
            sm.write_text(s, encoding="utf-8")
        print(f"sitemap +{added} urls")

        master = ROOT / "index.html"
        m = master.read_text(encoding="utf-8")
        book_dirs = [ROOT / b for b in all_book_dirs(ROOT)]
        block = S.build_block(Path("index.html"), "collection",
                              S.page_title(m), DESC_MASTER, doc_date(m),
                              S.ld_master(book_dirs))
        old = m
        m = re.sub(re.escape(S.MARK_S) + r".*?" + re.escape(S.MARK_E) + r"\n?",
                   "", m, flags=re.S)
        m = m.replace("</head>", block + "\n</head>", 1)
        if m != old:
            master.write_text(m, encoding="utf-8")
            print(f"master index JSON-LD books={len(book_dirs)} (updated)")
        else:
            print("master index 无变化")

        sync_catalog(ROOT)
        sync_readme(ROOT)

    print(f"books={len(done)} files_changed={stats['changed']} already_ok={stats['ok']}")


if __name__ == "__main__":
    main()
